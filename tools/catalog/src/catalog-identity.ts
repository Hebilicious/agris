import { createHash } from "node:crypto";
import { readdir, readFile } from "node:fs/promises";

import type { CatalogArtifact } from "./catalog.js";

/** Bump when the artifact's format changes what a name lookup or search answers for the same data. */
const CATALOG_IDENTITY_VERSION = "agris-catalog-identity:v3";

/**
 * The code the catalog answers with: the catalog subgraph, whose generated search index carries the folding and
 * trigram postings the tools built, and the Pearl Abyss modules it imports for locales and item IDs.
 */
const CATALOG_CODE_ROOTS = [
  { label: "catalog-subgraph/src/", url: new URL("../../../packages/catalog-subgraph/src/", import.meta.url) },
  { label: "pearl-abyss/src/", url: new URL("../../../packages/pearl-abyss/src/", import.meta.url) },
];

/** One source file the catalog answers with, by its path under its package's `src`. */
export interface CatalogCodeFile {
  readonly name: string;
  readonly text: string;
}

/**
 * The catalog's code, sorted by path: every `.ts` file under the catalog subgraph's and Pearl Abyss package's `src`,
 * the generated search index included, tests excluded. Read it after `catalog-tools:generate` has written the index.
 */
export async function readCatalogCode(): Promise<readonly CatalogCodeFile[]> {
  const files: CatalogCodeFile[] = [];
  for (const { label, url } of CATALOG_CODE_ROOTS) {
    const names = (await readdir(url, { recursive: true }))
      .filter((name) => name.endsWith(".ts") && !name.includes(".test."))
      .sort();
    for (const name of names) {
      files.push({ name: `${label}${name}`, text: await readFile(new URL(name, url), "utf8") });
    }
  }
  return files;
}

/**
 * One checksum for what the catalog answers in a release: every locale's `items.json` checksum, in locale order, and
 * the code that folds, indexes, matches, ranks and resolves those names. The gateway puts it in every cache key
 * (`CATALOG_DATA_IDENTITY` in `@agris/core`), so a release whose names or search change stores its answers under new
 * keys instead of serving the old release's for up to a year.
 */
export function catalogDataIdentity(sources: readonly CatalogArtifact[], code: readonly CatalogCodeFile[]): string {
  const hash = createHash("sha256").update(CATALOG_IDENTITY_VERSION);
  for (const source of sources) hash.update(`\n${source.manifest.locale}:${source.manifest.checksum}`);
  for (const file of code) hash.update(`\n${file.name}:${createHash("sha256").update(file.text).digest("hex")}`);
  return hash.digest("hex");
}

/** The generated module that carries the identity into `@agris/core`, and so into the gateway and cache Workers. */
export function serializeCatalogIdentityModule(identity: string): string {
  return [
    "// Generated by catalog-tools:generate from data/catalog and the catalog's code. Do not edit.",
    "",
    "/** A checksum of the catalog data and search code this release ships; part of every gateway cache key. */",
    `export const CATALOG_DATA_IDENTITY = "${identity}";`,
    "",
  ].join("\n");
}
