import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { composeSubgraphs } from "@graphql-mesh/compose-cli";
import {
  buildASTSchema,
  introspectionFromSchema,
  lexicographicSortSchema,
  parse,
  print,
  printSchema,
  type DocumentNode,
  type GraphQLSchema,
  type IntrospectionQuery,
} from "graphql";
import { canonicalizeGraphqlDocument, sha256Hex } from "../../../packages/core/dist/protocol/index.js";

import { createCatalogSubgraph } from "../../../packages/catalog-subgraph/dist/index.js";
import { createMarketSubgraph, subgraphSchemaFromSdl } from "../../../packages/market-subgraph/dist/index.js";

const toolRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifactRoot = resolve(toolRoot, "artifacts");
const marketUrl = "https://central-market-market.internal/graphql";
const catalogUrl = "https://central-market-catalog.internal/graphql";

const marketItemsWithCatalogDocument = `
  query MarketItemsWithCatalog($region: MarketRegion!, $ids: [ID!]!, $locale: ItemLocale = EN) {
    market(region: $region, locale: $locale) {
      region
      locale
      observedAt
      items(ids: $ids) {
        item {
          id
          locale
          name
          grade
        }
        isListed
        basePrice
        currentStock
        totalTrades
      }
    }
  }
`;

interface PersistedOperation {
  readonly document: string;
  readonly name: string;
}

interface PersistedOperationSource extends PersistedOperation {
  readonly artifactPath: string;
}

interface PersistedManifest {
  readonly operations: Readonly<Record<string, PersistedOperation>>;
  readonly version: 1;
}

export async function generateArtifacts(outputRoot = artifactRoot): Promise<void> {
  const marketSubgraph = createMarketSubgraph();
  const catalogSubgraph = createCatalogSubgraph();
  const marketSdl = canonicalSdl(marketSubgraph.sdl);
  const catalogSdl = canonicalSdl(catalogSubgraph.sdl);
  const composition = composeSubgraphs([
    { name: "market", schema: subgraphSchemaFromSdl(marketSdl), url: marketUrl },
    { name: "catalog", schema: subgraphSchemaFromSdl(catalogSdl), url: catalogUrl },
  ]);
  if (composition.errors !== undefined && composition.errors.length > 0) {
    throw new Error(`Central Market composition failed: ${composition.errors.join("; ")}`);
  }
  if (composition.supergraphSdl === undefined) throw new Error("Central Market composition returned no supergraph SDL");

  const supergraphSdl = canonicalSdl(composition.supergraphSdl);
  const clientSchema = publicClientSchema(supergraphSdl);
  const clientSdl = printSchema(lexicographicSortSchema(clientSchema));
  const introspection = introspectionFromSchema(lexicographicSortSchema(clientSchema));
  const persistedSources: readonly PersistedOperationSource[] = [
    {
      name: "MarketItemsWithCatalog",
      document: marketItemsWithCatalogDocument,
      artifactPath: "persisted/market-items-with-catalog.graphql",
    },
  ];
  const operationEntries = await Promise.all(
    persistedSources.map(async (source) => {
      const documentNode = parse(source.document, { noLocation: true });
      const canonicalDocument = canonicalizeGraphqlDocument(documentNode);
      return {
        source,
        documentSdl: print(documentNode),
        hash: await sha256Hex(canonicalDocument),
        operation: { name: source.name, document: canonicalDocument },
      };
    }),
  );
  const manifest: PersistedManifest = {
    version: 1,
    operations: Object.fromEntries(operationEntries.map(({ hash, operation }) => [hash, operation])),
  };

  await writeArtifact(outputRoot, "market-subgraph.graphql", `${marketSdl}\n`);
  await writeArtifact(outputRoot, "catalog-subgraph.graphql", `${catalogSdl}\n`);
  await writeArtifact(outputRoot, "supergraph.graphql", `${supergraphSdl}\n`);
  await writeArtifact(outputRoot, "client-schema.graphql", `${clientSdl}\n`);
  await writeArtifact(outputRoot, "client-schema.introspection.json", `${stableJson(introspection)}\n`);
  await Promise.all(
    operationEntries.map(({ source, documentSdl }) =>
      writeArtifact(outputRoot, source.artifactPath, `${documentSdl}\n`),
    ),
  );
  await writeArtifact(outputRoot, "persisted-operations.json", `${stableJson(manifest)}\n`);
  await writeArtifact(outputRoot, "gateway-schemas.ts", gatewaySchemasModule(`${clientSdl}\n`, `${supergraphSdl}\n`));
}

/**
 * The client schema and supergraph as a TypeScript module, so the gateway imports them as code: every bundler and
 * Node's loaders read it, where a `.graphql` text import needs a bundler rule.
 */
function gatewaySchemasModule(clientSdl: string, supergraphSdl: string): string {
  return [
    "// Generated by `moon run schema:generate` from client-schema.graphql and supergraph.graphql. Do not edit.",
    "",
    "/** The client schema every public and private caller's documents are validated against. */",
    `export const clientSchemaSdl: string = ${JSON.stringify(clientSdl)};`,
    "",
    "/** The composed supergraph Hive Gateway plans every operation over. */",
    `export const supergraphSdl: string = ${JSON.stringify(supergraphSdl)};`,
    "",
  ].join("\n");
}

function canonicalSdl(sdl: string): string {
  return print(parse(sdl, { noLocation: true }));
}

function publicClientSchema(supergraphSdl: string): GraphQLSchema {
  const document = parse(supergraphSdl, { noLocation: true });
  const filtered: DocumentNode = {
    ...document,
    definitions: document.definitions
      .filter((definition) => !isFederationHelperDefinition(definition))
      .map((definition) => stripFederationDetails(definition)),
  };
  const schema = buildASTSchema(filtered, { assumeValidSDL: true });
  return schema;
}

function isFederationHelperDefinition(definition: DocumentNode["definitions"][number]): boolean {
  if (definition.kind === "DirectiveDefinition") return true;
  if (!("name" in definition) || definition.name === undefined) return false;
  return (
    ["_Any", "_Entity", "_FieldSet", "_Service", "_join__Graph"].includes(definition.name.value) ||
    definition.name.value.startsWith("join__") ||
    definition.name.value.startsWith("link__")
  );
}

function stripFederationDetails<T extends DocumentNode["definitions"][number]>(definition: T): T {
  if (definition.kind === "ObjectTypeDefinition" || definition.kind === "ObjectTypeExtension") {
    // SAFETY: The kind guard narrows T to object definitions; replacing only directives and fields preserves that definition subtype.
    return {
      ...definition,
      directives: [],
      fields: definition.fields
        ?.filter((field) => field.name.value !== "_entities" && field.name.value !== "_service")
        .map((field) => ({ ...field, directives: [] })),
    } as T;
  }
  if (
    definition.kind === "SchemaDefinition" ||
    definition.kind === "SchemaExtension" ||
    definition.kind === "InterfaceTypeDefinition" ||
    definition.kind === "InputObjectTypeDefinition" ||
    definition.kind === "EnumTypeDefinition" ||
    definition.kind === "UnionTypeDefinition" ||
    definition.kind === "ScalarTypeDefinition" ||
    definition.kind === "DirectiveDefinition"
  ) {
    // SAFETY: The owning guard or fixture establishes { ...definition, directives: [] } conforms to T before this statement uses it.
    return { ...definition, directives: [] } as T;
  }
  return definition;
}

function stableJson(value: IntrospectionQuery | PersistedManifest): string {
  return JSON.stringify(
    value,
    /* BOUNDARY: Validates or normalizes external data before owned code consumes it. */ (_key, nestedValue: unknown) =>
      nestedValue,
    2,
  );
}

async function writeArtifact(root: string, relativePath: string, contents: string): Promise<void> {
  const target = resolve(root, relativePath);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, contents, "utf8");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  void generateArtifacts().catch(
    /* BOUNDARY: Validates or normalizes external data before owned code consumes it. */ (error: unknown) => {
      console.error(error instanceof Error ? (error.stack ?? error.message) : String(error));
      process.exitCode = 1;
    },
  );
}
